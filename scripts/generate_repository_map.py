#!/usr/bin/env python3
"""Generate the repository map document.

Usage:
    python scripts/generate_repository_map.py
"""
from __future__ import annotations

import os
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "v6" / "repository-map.md"

SECTIONS = [
    ("Core Source", ["agent_workbench", "v6", "core", "services", "workers", "tools"]),
    ("Documentation", ["docs"]),
    ("Tests", ["tests"]),
    ("Build & Scripts", ["scripts", "main.py", "agent_workbench.spec", "requirements.txt"]),
    ("Configuration", ["config", "pytest.ini", ".gitignore"]),
]


def _list_directory(path: Path, prefix: str = "") -> list[str]:
    lines: list[str] = []
    if not path.is_dir():
        return lines
    try:
        entries = sorted(
            [p for p in path.iterdir() if not p.name.startswith(".") and p.name != "__pycache__"],
            key=lambda p: (p.is_file(), p.name.lower()),
        )
    except PermissionError:
        return lines

    for entry in entries:
        marker = "📄" if entry.is_file() else "📁"
        lines.append(f"{prefix}{marker} {entry.name}")
        if entry.is_dir():
            lines.extend(_list_directory(entry, prefix + "    "))
    return lines


def generate() -> str:
    lines: list[str] = [
        "# V6 Repository Map",
        "",
        "> Auto-generated by `scripts/generate_repository_map.py`.",
        "> This map provides a high-level overview of the repository structure for AI retrieval, code review, and new contributors.",
        "",
        "## Top-Level Layout",
        "",
        "```text",
        "agent_workbench/          # V6 Agent Workbench application",
        "v6/                       # V6 Framework Core",
        "core/                     # Shared core utilities",
        "services/                 # Application services",
        "workers/                  # Background workers",
        "tools/                    # Tool implementations",
        "scripts/                  # Repository and build scripts",
        "tests/                    # Test suite",
        "config/                   # Configuration templates and defaults",
        "docs/                     # Documentation",
        "    v6/",
        "        runtime-kernel-spec.md",
        "        runtime-glossary.md",
        "        repository-governance.md",
        "        repository-map.md",
        "        SPEC.md",
        "        ROADMAP.md",
        "    archive/              # Historical documents worth keeping",
        "README.md",
        "PROJECT_BLUEPRINT.md",
        "PROJECT_LINEAGE.md",
        "CHANGELOG.md",
        "main.py",
        "agent_workbench.spec",
        "requirements.txt",
        "pytest.ini",
        ".gitignore",
        "```",
        "",
    ]

    for title, items in SECTIONS:
        lines.append(f"## {title}")
        lines.append("")
        for item in items:
            path = ROOT / item
            if not path.exists():
                continue
            marker = "📄" if path.is_file() else "📁"
            lines.append(f"{marker} {item}")
            if path.is_dir():
                lines.extend(_list_directory(path, "    "))
        lines.append("")

    lines.extend([
        "## Governance",
        "",
        "- For repository rules, see [`repository-governance.md`](./repository-governance.md).",
        "- For Runtime architecture, see [`runtime-kernel-spec.md`](./runtime-kernel-spec.md).",
        "- For terminology, see [`runtime-glossary.md`](./runtime-glossary.md).",
        "",
    ])

    return "\n".join(lines)


def main() -> int:
    content = generate()
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
